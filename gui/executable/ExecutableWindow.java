    public void closeExecutable()
    {
        // Close the open executable window after user confirmation
        
        if (closingWindow == false)
        {
            int selectionOption = JOptionPane.showConfirmDialog(this, "Are you sure you want to close this executable?", "Close Executable", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            if (selectionOption == JOptionPane.YES_OPTION)
            {
                try
                {
                    closingWindow = true;
                    this.setClosed(true);
                }
                catch (Exception errorReport)
                {
                    // This is a normal result of the closing of an internal window. Nothing should be done.
                }
            }       
        }
    }

