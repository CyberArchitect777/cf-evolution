    public ExecutableWindow(Executable selectedExecutable, String executableFileName, MainGUI origContainer) 
    {
        super("Executable File: " + executableFileName);
        fileName = executableFileName;
        initComponents();
        setContentPane(executableEditorWindow);
        currentExecutable = selectedExecutable;
        appFrame = origContainer;
        executableSelector = new ExecutableTreeSelector(executableEditorWindow, this);
        cardLayout = new CardLayout();
        multiPageContainer = new JPanel();
        multiPageContainer.setLayout(cardLayout);
        executableEditorPane.setLeftComponent(executableSelector);
        executableEditorPane.setRightComponent(multiPageContainer);
        gameOptions = new GameOptionsPanel(currentExecutable.getGameOptions());
        gameSettings = new GameSettingsPanel(currentExecutable.getGameSettings());
        gamePoints = new GamePointsPanel(currentExecutable.getGamePoints(), currentExecutable.returnGameVersionID()); 
        gameDrivers = new GameDriversPanel(currentExecutable.getGameDrivers());
        gameTeams = new GameTeamsPanel(currentExecutable.getGameTeams(), currentExecutable.getGameDrivers());
        ExecutableInfoPanel executableInfo = new ExecutableInfoPanel(currentExecutable.returnGameVersionString());
        multiPageContainer.add("Executable Info", executableInfo);
        multiPageContainer.add("Game Settings", gameSettings);
        multiPageContainer.add("Game Options", gameOptions);
        multiPageContainer.add("Points", gamePoints);
        multiPageContainer.add("Drivers", gameDrivers);
        multiPageContainer.add("Teams", gameTeams);
        ((CardLayout)multiPageContainer.getLayout()).show(multiPageContainer, "Executable Info");
        executableSelector.setVisible(true);
        multiPageContainer.setVisible(true);
        addInternalFrameListener(this); // Listener for internal frame closing events
        closingWindow = false; // Boolean value for detecting if closing occurs and then blocks any further events
        this.setDefaultCloseOperation(DO_NOTHING_ON_CLOSE); // Handle close operations manually        
    }
    
